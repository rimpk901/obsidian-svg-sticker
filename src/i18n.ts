export type TranslationKey = keyof typeof translations.en;

export function resolveLanguage(language: StickerLanguage) {
  if (language !== "auto") return language;

  const obsidianLanguage = getLanguage().toLowerCase();

  if (obsidianLanguage.startsWith("ru")) return "ru";
  if (obsidianLanguage.startsWith("ko")) return "ko";
  if (obsidianLanguage.startsWith("zh")) return "zh";

  return "en";
}

export function createTranslator(language: StickerLanguage) {
  const current = translations[resolveLanguage(language)];

  return (key: TranslationKey): string => current[key];
}
